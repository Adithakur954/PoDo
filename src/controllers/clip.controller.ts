import type { Request, Response } from "express";
import { unlink, mkdir, rm } from "node:fs/promises";
import { randomUUID } from "node:crypto";
import { createClipPlan } from "../services/clip.service.js";
import { downloadYouTubeVideo } from "../services/youtube.service.js";
import { clipPlanSchema, processVideoSchema } from "../schemas/clip.schemas.js";
import {
  getVideoDuration,
  createVideoClip,
} from "../services/video.service.js";

import { uploadVideoToYouTube } from "../services/youtube-upload.service.js";

interface GeneratedClip {
  part: number;
  start: number;
  duration: number;
  path: string;
}

interface UploadedClip {
  part: number;
  videoId: string;
  url: string;
}

export function createClipPlanController(req: Request, res: Response): void {
  // Here, you would typically extract the necessary data from the request body,
  // validate it, and then call the createClipPlan function from your service layer.
  // For demonstration purposes, we'll just return a placeholder response.

  const result = clipPlanSchema.safeParse(req.body); // safeParse will validate the input against the schema and return an object with success and data or error properties. and the req will parse json becuase in app.ts we have used express.json() middleware which will parse the incoming request body as JSON and make it available in req.body.

  if (!result.success) {
    res.status(400).json({
      success: false,
      message: "Invalid Request Data",
      errors: result.error.flatten(),
    });

    return;
  }

  const plan = createClipPlan(result.data);

  res.status(200).json({
    success: true,
    message: "Clip plan created successfully",
    data: plan,
  });
}

export async function processVideoController(
  req: Request,
  res: Response,
): Promise<void> {
  console.log("YouTube URL:", req.body.youtubeUrl);

  if (!req.file && !req.body.youtubeUrl) {
    res.status(400).json({
      success: false,
      message: "Video file or YouTube URL is required",
    });
    return;
  }

  // Validate the multipart/form-data fields
  const result = processVideoSchema.safeParse({
    clipDuration: req.body.clipDuration,
    youtubeUrl: req.body.youtubeUrl,
  });

  if (!result.success) {
    res.status(400).json({
      success: false,
      message: "Invalid clip duration",
      errors: result.error.flatten(),
    });
    return;
  }
  let jobDir: string | undefined;
  let sourceVideoPath: string;
  let allUploadsSucceeded = false;
  let uploadedClips: UploadedClip[] = [];

  if (req.file) {
    sourceVideoPath = req.file.path;
  } else if (result.data.youtubeUrl) {
    // If a YouTube URL is provided, download the video first
    const youtubePath = `tmp/youtube-${randomUUID()}.mp4`;
    await downloadYouTubeVideo(result.data.youtubeUrl, youtubePath);

    sourceVideoPath = youtubePath;
  } else {
    res.status(400).json({
      success: false,
      message: "Video file or YouTube URL is required",
    });
    return;
  }

  try {
    // Get the actual video duration using FFprobe
    const duration = await getVideoDuration(sourceVideoPath);

    // Create the clip plan using the real video duration
    const plan = createClipPlan({
      totalDuration: duration,
      clipDuration: result.data.clipDuration,
    });

    const generatedClips: GeneratedClip[] = [];
    const jobId = randomUUID();

    console.log("Job ID:", jobId);

    jobDir = `tmp/jobs/${jobId}`;

    await mkdir(jobDir, { recursive: true });

    console.log("Job directory:", jobDir);

    for (const clip of plan.clips) {
      const output = `${jobDir}/clip-${clip.part}.mp4`;

      console.log(
        `Creating clip ${clip.part}: start=${clip.start}, duration=${clip.duration}`,
      );

      await createVideoClip(sourceVideoPath, output, clip.start, clip.duration);

      generatedClips.push({
        part: clip.part,
        start: clip.start,
        duration: clip.duration,
        path: output,
      });
    }

    for (const clip of generatedClips) {
      console.log(`Uploading clip ${clip.part} to YouTube...`);

      const videoId = await uploadVideoToYouTube(
        clip.path,
        `PoDo Clip ${clip.part}`,
        `Clip ${clip.part} generated by PoDo.`,
      );

      uploadedClips.push({
        part: clip.part,
        videoId,
        url: `https://www.youtube.com/watch?v=${videoId}`,
      });

      console.log(`Clip ${clip.part} uploaded successfully.`);
    }
    allUploadsSucceeded = true;

    if (allUploadsSucceeded && jobDir) {
      await rm(jobDir, { recursive: true, force: true });
      console.log("All uploads succeeded. Generated clips deleted.");
    }

    res.status(200).json({
      success: true,
      message: "Video processed and uploaded successfully",
      data: {
        filename: req.file?.originalname ?? result.data.youtubeUrl,
        ...plan,
        generatedClips,
        uploadedClips,
      },
    });
  } catch (error) {
    console.error("Video processing or upload error:", error);

    res.status(500).json({
      success: false,
      message: "Video processing or upload failed",
      error: error instanceof Error ? error.message : String(error),
      jobDir,
      uploadedClips,
    });
  } finally {
    try {
      await unlink(sourceVideoPath);
    } catch (error) {
      console.error("Could not delete source video:", error);
    }
  }
}
